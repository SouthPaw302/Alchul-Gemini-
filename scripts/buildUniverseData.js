import fs from 'fs';
import path from 'path';

const contentDir = path.resolve('src/content/alchul');

function getFiles(dir, prefix = '') {
  let results = [];
  const list = fs.readdirSync(dir);
  for (const file of list) {
    const fullPath = path.join(dir, file);
    const relPath = prefix ? `${prefix}/${file}` : file;
    const stat = fs.statSync(fullPath);
    if (stat.isDirectory()) {
      results = results.concat(getFiles(fullPath, relPath));
    } else if (file.endsWith('.md')) {
      results.push({
        path: relPath,
        name: file,
        fullPath
      });
    }
  }
  return results;
}

const mdFiles = getFiles(contentDir);
const filesData = mdFiles.map(f => {
  const content = fs.readFileSync(f.fullPath, 'utf8');
  const firstLine = content.split('\n').find(l => l.startsWith('# ')) || `# ${f.name}`;
  const title = firstLine.replace(/^#\s+/, '').trim();
  
  // Categorize
  let category = 'Core Canon';
  if (f.path.startsWith('RESEARCH/')) category = 'Real Research';
  else if (f.path.startsWith('WRITING/')) category = 'Chronicles & Prose';
  else if (f.path.startsWith('ARCHIVE/')) category = 'Project Archives';
  else if (f.name === 'AGENT_BOOT.md' || f.name === 'README.md') category = 'Authoritative Protocols';

  return {
    id: f.path.replace(/\//g, '_').replace('.md', ''),
    path: f.path,
    filename: f.name,
    title,
    category,
    content
  };
});

const tsCode = `// Auto-generated by scripts/buildUniverseData.js
export interface UniverseFile {
  id: string;
  path: string;
  filename: string;
  title: string;
  category: 'Core Canon' | 'Real Research' | 'Chronicles & Prose' | 'Project Archives' | 'Authoritative Protocols';
  content: string;
}

export const UNIVERSE_FILES: UniverseFile[] = ${JSON.stringify(filesData, null, 2)};
`;

fs.mkdirSync(path.resolve('src/data'), { recursive: true });
fs.writeFileSync(path.resolve('src/data/universeData.ts'), tsCode);
console.log(`Generated src/data/universeData.ts with ${filesData.length} files.`);
